#!/usr/bin/env node
// Build-time generator: GeoNames cities (pop > 150K) → src/civic/cities.ts
// Downloads cities15000.zip from GeoNames, filters, and emits a static module.
// Same pattern as fetch-civic-actions.mjs — runs at build time, never at runtime.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createWriteStream, createReadStream, unlinkSync, mkdtempSync } from 'node:fs';
import { pipeline } from 'node:stream/promises';
import { createInterface } from 'node:readline';
import { tmpdir } from 'node:os';
import { execSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, '..', 'src', 'civic', 'cities.ts');
const MIN_POPULATION = 150_000;
const GEONAMES_URL = 'https://download.geonames.org/export/dump/cities15000.zip';

async function downloadFile(url, dest) {
  const resp = await fetch(url);
  if (!resp.ok) throw new Error(`Download failed: ${resp.status}`);
  await pipeline(resp.body, createWriteStream(dest));
}

async function fetchCities() {
  console.log('Downloading GeoNames cities15000.zip...');
  const tmp = mkdtempSync(join(tmpdir(), 'geonames-'));
  const zipPath = join(tmp, 'cities15000.zip');
  const txtPath = join(tmp, 'cities15000.txt');

  await downloadFile(GEONAMES_URL, zipPath);
  execSync(`unzip -o -q "${zipPath}" -d "${tmp}"`);

  console.log(`Parsing cities with population > ${MIN_POPULATION.toLocaleString()}...`);
  const cities = [];
  const rl = createInterface({ input: createReadStream(txtPath) });

  for await (const line of rl) {
    const cols = line.split('\t');
    // GeoNames TSV: 0=geonameid, 1=name, 2=asciiname, 4=lat, 5=lng, 8=countryCode, 14=population
    const name = cols[2]; // ASCII name for safe matching
    const lat = parseFloat(cols[4]);
    const lng = parseFloat(cols[5]);
    const country = cols[8];
    const pop = parseInt(cols[14], 10);

    if (pop >= MIN_POPULATION && name && country) {
      cities.push({ name, lat: +lat.toFixed(4), lng: +lng.toFixed(4), country, pop });
    }
  }

  // Also collect alternate spellings from asciiname vs name column
  // Sort by population descending for deterministic output
  cities.sort((a, b) => b.pop - a.pop);

  // Cleanup
  try { unlinkSync(zipPath); } catch {}
  try { unlinkSync(txtPath); } catch {}

  console.log(`  Found ${cities.length} cities with population > ${MIN_POPULATION.toLocaleString()}`);
  return cities;
}

function generateModule(cities) {
  let ts = `// Auto-generated by scripts/fetch-cities.mjs — DO NOT EDIT\n`;
  ts += `// GeoNames cities with population > ${MIN_POPULATION.toLocaleString()}\n`;
  ts += `// ${cities.length} entries, generated ${new Date().toISOString().slice(0, 10)}\n\n`;
  ts += `export interface GazetteerCity {\n`;
  ts += `  name: string;\n`;
  ts += `  lat: number;\n`;
  ts += `  lng: number;\n`;
  ts += `  country: string;\n`;
  ts += `  pop: number;\n`;
  ts += `}\n\n`;

  // Build a name → index lookup for fast matching
  ts += `export const CITIES: GazetteerCity[] = [\n`;
  for (const c of cities) {
    const safeName = c.name.replace(/'/g, "\\'");
    ts += `  { name: '${safeName}', lat: ${c.lat}, lng: ${c.lng}, country: '${c.country}', pop: ${c.pop} },\n`;
  }
  ts += `];\n\n`;

  // Pre-build a lowercase name → index map for O(1) lookup
  ts += `export const CITY_NAME_INDEX: Map<string, number[]> = new Map();\n`;
  ts += `for (let i = 0; i < CITIES.length; i++) {\n`;
  ts += `  const key = CITIES[i].name.toLowerCase();\n`;
  ts += `  const arr = CITY_NAME_INDEX.get(key) ?? [];\n`;
  ts += `  arr.push(i);\n`;
  ts += `  CITY_NAME_INDEX.set(key, arr);\n`;
  ts += `}\n`;

  return ts;
}

const cities = await fetchCities();
const module = generateModule(cities);
writeFileSync(OUT_PATH, module, 'utf-8');
console.log(`Written to ${OUT_PATH}`);
